import { ProductSpec, QuartzProduct } from '../types';

type RawQuartzProduct = {
  id: number | string;
  name: string;
  collection: string;
  subcategory: string;
  thickness: string[];
  size: string;
  finish: string;
  description: string;
  image: string;
  inStock?: boolean;
  features?: string[];
  gallery?: string[];
  slug?: string;
};

const DEFAULT_BRAND = 'COPPOLA QUARTZ';
const DEFAULT_CATEGORY = 'quartz' as const;

const normalizeSlug = (name: string) => {
  return name
    .trim()
    .replace(/Quartz$/i, '')
    .replace(/[^A-Za-z0-9]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
    .toLowerCase();
};

const fallbackDescription = (product: RawQuartzProduct) => {
  const base = `${product.name} from our ${product.collection} collection features a ${product.finish.toLowerCase()} finish on slabs sized ${product.size}.`;
  if (product.features && product.features.length) {
    return `${base} Highlights: ${product.features.join(', ')}.`;
  }
  return base;
};

const toSpecs = (product: RawQuartzProduct): ProductSpec[] => [
  { label: 'Thickness', value: product.thickness.join(', ') },
  { label: 'Size', value: product.size },
  { label: 'Finish', value: product.finish },
  { label: 'Material', value: 'Premium Quartz' },
  ...(product.collection ? [{ label: 'Collection', value: product.collection }] : [])
];

